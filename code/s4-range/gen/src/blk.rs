// Blocked-interval modules (two certificate types) and their Rust mirror.
// blkgen A BLO BHI TCFILE OUTFILE [corrupt IDX | drop IDX | droptc IDX]
// blkverify FILE...      (mirror of S4Loop2.rangeB2 on the TEXT of the module)
use super::*;
use std::collections::HashMap;

// ---- mirror of TC.tcOK (same algorithm as the Lean code) ----
fn wv(q: u64, v: u64, n: u64) -> u64 { (10 * v * n + 8 * q) % (10 * q) }
fn tabm(m2: u64, l2: u64, ws: &[u64]) -> Vec<u128> {
    (0..m2).map(|p| { let mut m = 0u128; for (k, &w) in ws.iter().enumerate() { if (p + w) % m2 <= l2 { m |= 1u128 << k; } } m }).collect()
}
fn dedup(l: &[u128]) -> Vec<u128> { let mut out: Vec<u128> = vec![]; for &x in l { if out.last() != Some(&x) { out.push(x); } } out }
pub fn tc_ok(v: &[u64; 4], q: u64, times: &[u64]) -> bool {
    if q == 0 || v[0] == 0 { return false; }
    let mut bs: Vec<[u64; 3]> = vec![];
    for &n in times { if wv(q, v[0], n) <= 6 * q { bs.push([wv(q, v[1], n), wv(q, v[2], n), wv(q, v[3], n)]); } }
    if bs.len() > 127 { return false; }
    let m2 = 10 * q; let l2 = 6 * q;
    let col = |c: usize| -> Vec<u64> { bs.iter().map(|b| b[c]).collect() };
    let d1 = dedup(&tabm(m2, l2, &col(0))); let d2 = dedup(&tabm(m2, l2, &col(1))); let d3 = dedup(&tabm(m2, l2, &col(2)));
    for &x1 in &d1 {
        let masked: Vec<u128> = d2.iter().map(|&y| x1 & y).collect();
        for &s in &dedup(&masked) { for &x3 in &d3 { if s & x3 == 0 { return false; } } }
    }
    true
}

enum Rec2 {
    D0 { vb: u32, vc: u32, vd: u32, k: K3 },
    Tc { vb: u32, vc: u32, vd: u32, q: u64, times: Vec<u64> },
    Pre { vb: u32, vc: u32, vd: u32 },
}

fn tc_lit(v: &V4, q: u64, times: &[u64]) -> String {
    format!(".tc {} {} {} {} [{}]", v[1], v[2], v[3], q, times.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(", "))
}

fn load_tc(path: &str) -> HashMap<(u32, u32, u32, u32), (u64, Vec<u64>)> {
    let mut m = HashMap::new();
    let txt = fs::read_to_string(path).unwrap();
    for line in txt.lines() {
        let w: Vec<&str> = line.split_whitespace().collect();
        if w.len() < 6 || w[4] == "NONE" { continue; }
        let v: Vec<u32> = w[0..4].iter().map(|x| x.parse().unwrap()).collect();
        let mut q = 0u64; let mut times: Vec<u64> = vec![];
        for tok in &w[4..] {
            if let Some(r) = tok.strip_prefix("q=") { q = r.parse().unwrap(); }
            if let Some(r) = tok.strip_prefix("times=") { times = r.split(',').filter(|s| !s.is_empty()).map(|s| s.parse().unwrap()).collect(); }
        }
        m.insert((v[0], v[1], v[2], v[3]), (q, times));
    }
    m
}

pub fn blkgen(a: &[String]) {
    let aa: u32 = a[0].parse().unwrap(); let blo: u32 = a[1].parse().unwrap(); let bhi: u32 = a[2].parse().unwrap();
    let tcm = load_tc(&a[3]); let out = a[4].clone();
    let (mut mode, mut idx) = ("none".to_string(), 0usize);
    if a.len() > 6 { mode = a[5].clone(); idx = a[6].parse().unwrap(); }
    let n = bhi - blo + 1;
    let mut recs: Vec<String> = vec![];
    let (mut en, mut pr, mut cl, mut nd0, mut ntc) = (0u64, 0u64, 0u64, 0u64, 0u64);
    let mut missing: Vec<[u32; 4]> = vec![];
    let mut pres: Vec<(V4, u64, Vec<u64>)> = vec![];
    for_range(aa, blo, n, &mut |a0, b, c, d| {
        en += 1;
        if gcd(gcd(a0, b), gcd(c, d)) != 1 { return; }
        pr += 1;
        if class_b([a0, b, c, d]) { cl += 1; return; }
        let vv: V4 = [a0 as i64, b as i64, c as i64, d as i64];
        match find_cert(&vv) {
            Some(k) => { recs.push(lean_lit(&vv, &k)); nd0 += 1; }
            None => match tcm.get(&(a0, b, c, d)) {
                Some((q, t)) => { recs.push(format!(".pre {} {} {}", b, c, d)); pres.push((vv, *q, t.clone())); ntc += 1; }
                None => missing.push([a0, b, c, d]),
            },
        }
    });
    if !missing.is_empty() { eprintln!("REFUSED: {} vectors without any certificate, e.g. {:?}", missing.len(), &missing[..missing.len().min(5)]); std::process::exit(2); }
    if mode == "corrupt" {
        // change the first d0 record at or after idx: k1[0] += 1
        let mut i = idx; while !recs[i].starts_with(".d0 ") { i += 1; }
        let mut parts: Vec<String> = recs[i].split(' ').map(|s| s.to_string()).collect();
        let t = parts[4].trim_matches(|c| c == '(' || c == ')').parse::<i64>().unwrap() + 1;
        parts[4] = if t < 0 { format!("({})", t) } else { format!("{}", t) };
        recs[i] = parts.join(" ");
    } else if mode == "drop" { recs.remove(idx); }
    else if mode == "droptc" {
        // remove the first numerator of time cover number idx
        pres[idx].2.remove(0);
    }
    let id = format!("{}_{}_{}", aa, blo, bhi);
    let mut s = String::new();
    s.push_str(&format!("/-\n# generated by s4blk (tc_cert/blk): BLOCKED range a={} b in [{}, {}], {} depth-0 records + {} time-cover records ({})\n-/\nimport LRSpectrumFull.S4Loop2\n\nnamespace LRSpectrumFull\nnamespace D0\n\n", aa, blo, bhi, nd0, ntc, mode));
    for (v, q, t) in &pres {
        let nm = format!("{}_{}_{}_{}", v[0], v[1], v[2], v[3]);
        s.push_str(&format!("theorem tcv_{nm} : TC.tcOK {} {} {} {} {} [{}] = true := by decide +kernel\n", v[0], v[1], v[2], v[3], q, t.iter().map(|x| x.to_string()).collect::<Vec<_>>().join(", "), nm = nm));
        s.push_str(&format!("theorem tcs_{nm} : S4 ![{}, {}, {}, {}] := TC.tc_sound {} {} {} {} {} _ tcv_{nm}\n", v[0], v[1], v[2], v[3], v[0], v[1], v[2], v[3], q, nm = nm));
    }
    s.push_str(&format!("\ndef preL_{id} : List (ℕ × ℕ × ℕ × ℕ) := [{}]\n\n", pres.iter().map(|(v, _, _)| format!("({}, {}, {}, {})", v[0], v[1], v[2], v[3])).collect::<Vec<_>>().join(", "), id = id));
    if pres.is_empty() {
        s.push_str(&format!("theorem preOK_{id} : PreOK preL_{id} := by\n  intro x hx\n  simp [preL_{id}] at hx\n\n", id = id));
    } else {
        let pat = vec!["rfl"; pres.len()].join(" | ");
        let ex = pres.iter().map(|(v, _, _)| format!("tcs_{}_{}_{}_{}", v[0], v[1], v[2], v[3])).collect::<Vec<_>>().join(", ");
        s.push_str(&format!("theorem preOK_{id} : PreOK preL_{id} := by\n  intro x hx\n  simp only [preL_{id}, List.mem_cons, List.not_mem_nil, or_false] at hx\n  rcases hx with {pat}\n  exacts [{ex}]\n\n", id = id, pat = pat, ex = ex));
    }
    s.push_str(&format!("set_option maxRecDepth 1000000 in\ndef certs_{} : List Cert2 := [\n", id));
    for (i, r) in recs.iter().enumerate() { s.push_str("  "); s.push_str(r); if i + 1 < recs.len() { s.push_str(",\n"); } else { s.push('\n'); } }
    s.push_str("]\n\n");
    s.push_str(&format!("theorem rng_{id} : rangeB2 preL_{id} {a} {blo} {n} certs_{id} = true := by decide +kernel\n\n", id = id, a = aa, blo = blo, n = n));
    s.push_str(&format!("theorem s4_blk_{id} : ∀ b c d : ℕ, {blo} ≤ b → b < {blo} + {n} → b < c → c < d → {a} + b + c + d ≤ 195 →\n    Nat.gcd (Nat.gcd {a} b) (Nat.gcd c d) = 1 → S4 ![{a}, b, c, d] :=\n  rangeOK2_sound preOK_{id} (by norm_num) (by norm_num) rng_{id}\n\n", id = id, a = aa, blo = blo, n = n));
    s.push_str(&format!("#print axioms s4_blk_{}\n\nend D0\nend LRSpectrumFull\n", id));
    fs::write(&out, s).unwrap();
    println!("BLKGEN {} enumerated {} primitive {} classB {} d0 {} tc {} -> {}", id, en, pr, cl, nd0, ntc, out);
}

fn parse2(path: &str) -> Result<(u32, u32, u32, Vec<Rec2>, std::collections::HashSet<(u32,u32,u32,u32)>), String> {
    let txt = fs::read_to_string(path).map_err(|e| format!("{}: {}", path, e))?;
    for bad in ["sorry", "native_decide", "ofReduceBool", "axiom ", "unsafe", "implemented_by", "admit"] {
        if txt.contains(bad) { return Err(format!("forbidden token {}", bad)); }
    }
    let mut hdr: Option<(u32, u32, u32)> = None; let mut recs: Vec<Rec2> = vec![]; let mut preset = std::collections::HashSet::new();
    for line in txt.lines() {
        let t = line.trim().trim_end_matches(',');
        if t.starts_with("theorem rng_") {
            let p = t.find("rangeB2 ").ok_or("no rangeB2")? + 8;
            let w: Vec<&str> = t[p..].split_whitespace().skip(1).take(3).collect();
            hdr = Some((w[0].parse().unwrap(), w[1].parse().unwrap(), w[2].parse().unwrap()));
        }
        if t.starts_with(".d0 ") {
            let cleaned: String = t.chars().filter(|&c| c != '(' && c != ')').collect();
            let w: Vec<&str> = cleaned.split_whitespace().collect();
            if w.len() != 16 { return Err(format!("bad d0 record {}", t)); }
            let mut k = [[0i64; 4]; 3];
            for l in 0..3 { for r in 0..4 { k[l][r] = w[4 + 4 * l + r].parse().map_err(|_| format!("bad int in {}", t))?; } }
            recs.push(Rec2::D0 { vb: w[1].parse().unwrap(), vc: w[2].parse().unwrap(), vd: w[3].parse().unwrap(), k });
        }
        if t.starts_with("theorem tcv_") {
            let p = t.find("TC.tcOK ").ok_or("no tcOK")? + 8;
            let lb = t.find('[').ok_or("no list")?; let rb = t.find(']').ok_or("no list")?;
            let h: Vec<u64> = t[p..lb].split_whitespace().map(|x| x.parse().unwrap()).collect();
            let times: Vec<u64> = t[lb + 1..rb].split(',').map(|s| s.trim()).filter(|s| !s.is_empty()).map(|s| s.parse().unwrap()).collect();
            if h.len() != 5 { return Err(format!("bad tcv {}", t)); }
            if tc_ok(&[h[0], h[1], h[2], h[3]], h[4], &times) { preset.insert((h[0] as u32, h[1] as u32, h[2] as u32, h[3] as u32)); }
        }
        if t.starts_with(".pre ") {
            let w: Vec<&str> = t.split_whitespace().collect();
            recs.push(Rec2::Pre { vb: w[1].parse().unwrap(), vc: w[2].parse().unwrap(), vd: w[3].parse().unwrap() });
        }
        if t.starts_with(".tc ") {
            let lb = t.find('[').ok_or("tc without list")?;
            let head: Vec<&str> = t[..lb].split_whitespace().collect();
            if head.len() != 5 { return Err(format!("bad tc record {}", t)); }
            let inner = &t[lb + 1..t.len() - 1];
            let times: Vec<u64> = inner.split(',').map(|s| s.trim()).filter(|s| !s.is_empty()).map(|s| s.parse().unwrap()).collect();
            recs.push(Rec2::Tc { vb: head[1].parse().unwrap(), vc: head[2].parse().unwrap(), vd: head[3].parse().unwrap(), q: head[4].parse().unwrap(), times });
        }
    }
    let (a, blo, n) = hdr.ok_or("no rangeB2 theorem line")?;
    Ok((a, blo, n, recs, preset))
}

fn simulate2(a: u32, blo: u32, n: u32, recs: &Vec<Rec2>, preset: &std::collections::HashSet<(u32,u32,u32,u32)>) -> Result<(usize, usize), String> {
    let mut i = 0usize; let mut err: Option<String> = None; let (mut nd, mut nt) = (0usize, 0usize);
    for_range(a, blo, n, &mut |a0, b, c, d| {
        if err.is_some() { return; }
        if gcd(gcd(a0, b), gcd(c, d)) != 1 { return; }
        if i < recs.len() {
            match &recs[i] {
                Rec2::D0 { vb, vc, vd, k } => if b == *vb && c == *vc && d == *vd && lean_ok(&[a0 as i64, b as i64, c as i64, d as i64], k) { i += 1; nd += 1; return; },
                Rec2::Pre { vb, vc, vd } => if b == *vb && c == *vc && d == *vd && preset.contains(&(a0, b, c, d)) { i += 1; nt += 1; return; },
                Rec2::Tc { vb, vc, vd, q, times } => if b == *vb && c == *vc && d == *vd && tc_ok(&[a0 as u64, b as u64, c as u64, d as u64], *q, times) { i += 1; nt += 1; return; },
            }
        }
        if class_b([a0, b, c, d]) { return; }
        err = Some(format!("vector ({},{},{},{}) neither certified by next record (index {}) nor classB", a0, b, c, d, i));
    });
    if let Some(e) = err { return Err(e); }
    if i != recs.len() { return Err(format!("{} records unconsumed", recs.len() - i)); }
    Ok((nd, nt))
}

pub fn blkverify(files: &[String]) {
    let mut bad = 0;
    for f in files {
        match parse2(f) {
            Err(e) => { println!("BLKVERIFY\t{}\tMIRROR_FALSE\t{}", f, e); bad += 1; }
            Ok((a, blo, n, recs, preset)) => match simulate2(a, blo, n, &recs, &preset) {
                Ok((nd, nt)) => println!("BLKVERIFY\t{}\ta={} blo={} n={} records={} (d0 {} tc {})\tMIRROR_TRUE", f, a, blo, n, recs.len(), nd, nt),
                Err(e) => { println!("BLKVERIFY\t{}\tMIRROR_FALSE\t{}", f, e); bad += 1; }
            },
        }
    }
    println!("BLKVERIFY SUMMARY files {} mirror_false {}", files.len(), bad);
}
