// block 2 additions to s4gen: plan (per (a,b) table), genall (uniform-name modules), verify (Rust mirror of
// rangeB on the TEXT of a module file), check (exactness of the partition manifest).
use super::*;
use std::collections::HashSet;

pub fn ident(a: u32, blo: u32, bhi: u32) -> String { format!("{}_{}_{}", a, blo, bhi) }
pub fn module_name(a: u32, blo: u32, bhi: u32) -> String { format!("S4R_{:02}_{:03}_{:03}", a, blo, bhi) }

fn tally(a: u32, blo: u32, n: u32) -> (u64, u64, u64, u64, u64) {
    // enumerated, primitive, classB, residual, certless
    let (mut en, mut pr, mut cl, mut re, mut nc) = (0u64, 0u64, 0u64, 0u64, 0u64);
    for_range(a, blo, n, &mut |a0, b, c, d| {
        en += 1;
        if gcd(gcd(a0, b), gcd(c, d)) != 1 { return; }
        pr += 1;
        if class_b([a0, b, c, d]) { cl += 1; return; }
        re += 1;
        let vv: V4 = [a0 as i64, b as i64, c as i64, d as i64];
        if find_cert(&vv).is_none() { nc += 1; }
    });
    (en, pr, cl, re, nc)
}

pub fn plan(maxs: u32, out: &str) {
    let mut f = fs::File::create(out).unwrap();
    writeln!(f, "a\tb\tenumerated\tprimitive\tclassB\tresidual\tnocert").unwrap();
    let (mut te, mut tp, mut tc, mut tr, mut tn) = (0u64, 0u64, 0u64, 0u64, 0u64);
    for aa in 1..=maxs {
        let n = full_n(aa);
        for b in aa + 1..aa + 1 + n {
            let (en, pr, cl, re, nc) = tally(aa, b, 1);
            if en == 0 { continue; }
            writeln!(f, "{}\t{}\t{}\t{}\t{}\t{}\t{}", aa, b, en, pr, cl, re, nc).unwrap();
            te += en; tp += pr; tc += cl; tr += re; tn += nc;
        }
    }
    println!("PLAN TOTAL enumerated {} primitive {} classB {} residual {} nocert {}", te, tp, tc, tr, tn);
}

fn module_text(aa: u32, blo: u32, bhi: u32, recs: &Vec<String>) -> String {
    let n = bhi - blo + 1;
    let id = ident(aa, blo, bhi);
    let mut s = String::new();
    s.push_str(&format!("/-\n# generated by s4gen block2 (s4_range/census_b): range a={} b in [{}, {}] (b < {}), {} depth-0 records\n-/\nimport LRSpectrumFull.S4Loop\n\nnamespace LRSpectrumFull\nnamespace D0\n\n", aa, blo, bhi, blo + n, recs.len()));
    s.push_str(&format!("set_option maxRecDepth 1000000 in\ndef certs_{} : List Cert := [\n", id));
    for (i, r) in recs.iter().enumerate() { s.push_str("  "); s.push_str(r); if i + 1 < recs.len() { s.push_str(",\n"); } else { s.push('\n'); } }
    s.push_str("]\n\n");
    s.push_str(&format!("theorem rng_{id} : rangeB {a} {blo} {n} certs_{id} = true := by decide +kernel\n\n", id = id, a = aa, blo = blo, n = n));
    s.push_str(&format!("theorem s4_range_{id} : ∀ b c d : ℕ, {blo} ≤ b → b < {blo} + {n} → b < c → c < d → {a} + b + c + d ≤ 195 →\n    Nat.gcd (Nat.gcd {a} b) (Nat.gcd c d) = 1 → S4 ![{a}, b, c, d] :=\n  rangeOK_sound (by norm_num) (by norm_num) rng_{id}\n\n", id = id, a = aa, blo = blo, n = n));
    s.push_str(&format!("#print axioms s4_range_{}\n\nend D0\nend LRSpectrumFull\n", id));
    s
}

/// part file: TSV with header line, columns a blo bhi (TODO modules only). dry = "dry" writes nothing.
pub fn genall(part: &str, outdir: &str, dry: bool) {
    let txt = fs::read_to_string(part).unwrap();
    let mut total_bytes = 0u64; let mut nmod = 0u64;
    for line in txt.lines().skip(1) {
        let f: Vec<&str> = line.split('\t').collect();
        let (aa, blo, bhi): (u32, u32, u32) = (f[0].parse().unwrap(), f[1].parse().unwrap(), f[2].parse().unwrap());
        let n = bhi - blo + 1;
        let mut recs: Vec<String> = vec![];
        let (mut en, mut pr, mut cl, mut nc) = (0u64, 0u64, 0u64, 0u64);
        for_range(aa, blo, n, &mut |a0, b, c, d| {
            en += 1;
            if gcd(gcd(a0, b), gcd(c, d)) != 1 { return; }
            pr += 1;
            if class_b([a0, b, c, d]) { cl += 1; return; }
            let vv: V4 = [a0 as i64, b as i64, c as i64, d as i64];
            match find_cert(&vv) { Some(k) => recs.push(lean_lit(&vv, &k)), None => nc += 1 }
        });
        if nc > 0 { eprintln!("REFUSED module a={} b {}..{}: {} certless vectors", aa, blo, bhi, nc); std::process::exit(2); }
        let text = module_text(aa, blo, bhi, &recs);
        let name = module_name(aa, blo, bhi);
        total_bytes += text.len() as u64; nmod += 1;
        if !dry { let path = format!("{}/{}.lean", outdir, name); if fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) { fs::write(&path, &text).unwrap(); } }
        println!("GEN\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}", name, aa, blo, bhi, en, pr, cl, recs.len(), text.len());
    }
    eprintln!("{} {} modules, total source bytes {}", if dry { "DRY" } else { "WROTE" }, nmod, total_bytes);
}

struct Rec { vb: u32, vc: u32, vd: u32, k: K3 }

fn parse_file(path: &str) -> Result<(u32, u32, u32, Vec<Rec>), String> {
    let txt = fs::read_to_string(path).map_err(|e| format!("{}: {}", path, e))?;
    for bad in ["sorry", "native_decide", "ofReduceBool", "axiom ", ".other"] {
        if txt.contains(bad) { return Err(format!("forbidden token {}", bad)); }
    }
    let mut hdr: Option<(u32, u32, u32)> = None;
    let mut recs: Vec<Rec> = vec![];
    for line in txt.lines() {
        let t = line.trim();
        if t.starts_with("theorem rng_") {
            let p = t.find("rangeB ").ok_or("no rangeB")? + 7;
            let w: Vec<&str> = t[p..].split_whitespace().take(3).collect();
            hdr = Some((w[0].parse().unwrap(), w[1].parse().unwrap(), w[2].parse().unwrap()));
        }
        if t.starts_with(".d0 ") {
            let cleaned: String = t.chars().filter(|&c| c != '(' && c != ')' && c != ',').collect();
            let w: Vec<&str> = cleaned.split_whitespace().collect();
            if w.len() != 16 { return Err(format!("bad record line {}", t)); }
            let mut k = [[0i64; 4]; 3];
            for l in 0..3 { for r in 0..4 { k[l][r] = w[4 + 4 * l + r].parse().map_err(|_| format!("bad int in {}", t))?; } }
            recs.push(Rec { vb: w[1].parse().unwrap(), vc: w[2].parse().unwrap(), vd: w[3].parse().unwrap(), k });
        }
    }
    let (a, blo, n) = hdr.ok_or("no rangeB theorem line")?;
    Ok((a, blo, n, recs))
}

/// mirror of S4Loop.rangeB: Ok(()) iff Lean's Bool would be true
fn simulate(a: u32, blo: u32, n: u32, recs: &Vec<Rec>) -> Result<(), String> {
    let mut i = 0usize; let mut err: Option<String> = None;
    for_range(a, blo, n, &mut |a0, b, c, d| {
        if err.is_some() { return; }
        if gcd(gcd(a0, b), gcd(c, d)) != 1 { return; }
        if i < recs.len() {
            let r = &recs[i];
            if b == r.vb && c == r.vc && d == r.vd && lean_ok(&[a0 as i64, b as i64, c as i64, d as i64], &r.k) { i += 1; return; }
        }
        if class_b([a0, b, c, d]) { return; }
        err = Some(format!("vector ({},{},{},{}) neither certified by next record (index {}) nor classB", a0, b, c, d, i));
    });
    if let Some(e) = err { return Err(e); }
    if i != recs.len() { return Err(format!("{} records unconsumed", recs.len() - i)); }
    Ok(())
}

pub fn verify(files: &[String]) {
    let mut bad = 0;
    for f in files {
        match parse_file(f) {
            Err(e) => { println!("VERIFY\t{}\tMIRROR_FALSE\t{}", f, e); bad += 1; }
            Ok((a, blo, n, recs)) => match simulate(a, blo, n, &recs) {
                Ok(()) => println!("VERIFY\t{}\ta={} blo={} n={} records={}\tMIRROR_TRUE", f, a, blo, n, recs.len()),
                Err(e) => { println!("VERIFY\t{}\tMIRROR_FALSE\t{}", f, e); bad += 1; }
            },
        }
    }
    println!("VERIFY SUMMARY files {} mirror_false {}", files.len(), bad);
}

/// manifest columns (header names): module a b_lo b_hi enumerated primitive records certless source_bytes sha256 status mirror theorem
pub fn check(manifest: &str, leandir: &str, maxs: u32) {
    let txt = fs::read_to_string(manifest).unwrap();
    let mut lines = txt.lines();
    let hdr: Vec<&str> = lines.next().unwrap().split('\t').collect();
    let col = |n: &str| hdr.iter().position(|h| *h == n).unwrap();
    let (cm, ca, cl, ch, ce, cp, cr, cc, cs) = (col("module"), col("a"), col("b_lo"), col("b_hi"), col("enumerated"), col("primitive"), col("records"), col("certless"), col("status"));
    let mut cover = vec![vec![0u32; 400]; 100];
    let (mut s_en, mut s_pr, mut s_rec_files, mut s_rec_blocked, mut s_nc) = (0u64, 0u64, 0u64, 0u64, 0u64);
    let mut problems = 0;
    let (mut n_todo, mut n_done, mut n_blk) = (0, 0, 0);
    let (mut p_todo, mut p_done, mut p_blk) = (0u64, 0u64, 0u64);
    for line in lines {
        if line.trim().is_empty() { continue; }
        let f: Vec<&str> = line.split('\t').collect();
        let a: u32 = f[ca].parse().unwrap(); let blo: u32 = f[cl].parse().unwrap(); let bhi: u32 = f[ch].parse().unwrap();
        let n = bhi - blo + 1;
        let (en, pr, _clb, re, nc) = tally(a, blo, n);
        let status = f[cs];
        if en != f[ce].parse::<u64>().unwrap() || pr != f[cp].parse::<u64>().unwrap() { println!("PROBLEM {} manifest enumerated/primitive differ: {} {} vs {} {}", f[cm], f[ce], f[cp], en, pr); problems += 1; }
        for b in blo..=bhi { cover[a as usize][b as usize] += 1; }
        s_en += en; s_pr += pr;
        match status {
            "TODO" | "DONE-probe" => {
                if status == "TODO" { n_todo += 1; p_todo += pr; } else { n_done += 1; p_done += pr; }
                let path = format!("{}/{}.lean", leandir, f[cm]);
                match parse_file(&path) {
                    Err(e) => { println!("PROBLEM {}: {}", f[cm], e); problems += 1; }
                    Ok((fa, fblo, fn_, recs)) => {
                        if fa != a || fblo != blo || fn_ != n { println!("PROBLEM {}: file range a={} blo={} n={} vs manifest {} {} {}", f[cm], fa, fblo, fn_, a, blo, n); problems += 1; }
                        if recs.len() as u64 != re || nc != 0 { println!("PROBLEM {}: file records {} vs residual {} certless {}", f[cm], recs.len(), re, nc); problems += 1; }
                        if let Err(e) = simulate(fa, fblo, fn_, &recs) { println!("PROBLEM {}: mirror false: {}", f[cm], e); problems += 1; }
                        s_rec_files += recs.len() as u64;
                    }
                }
            }
            "BLOCKED" => {
                n_blk += 1; p_blk += pr;
                if nc as u64 != f[cc].parse::<u64>().unwrap() { println!("PROBLEM blocked {} {} {}: certless {} vs manifest {}", a, blo, bhi, nc, f[cc]); problems += 1; }
                if nc == 0 { println!("PROBLEM blocked interval a={} b {}..{} has no certless vector", a, blo, bhi); problems += 1; }
                s_nc += nc; s_rec_blocked += re - nc;
                let _ = cr;
            }
            other => { println!("PROBLEM unknown status {}", other); problems += 1; }
        }
    }
    // independent universe: census-style triple loop (sum <= maxs), and pair coverage
    let mut univ_total = 0u64; let mut univ_en = 0u64;
    let mut univ_pairs: HashSet<(u32, u32)> = HashSet::new();
    for aa in 1..=maxs { for b in aa + 1..=maxs { if aa + b + b + 1 > maxs { break; }
        for c in b + 1..=maxs { if aa + b + c + c + 1 > maxs { break; }
            for d in c + 1..=maxs { if aa + b + c + d > maxs { break; }
                univ_en += 1; univ_pairs.insert((aa, b));
                if gcd(gcd(aa, b), gcd(c, d)) == 1 { univ_total += 1; } } } } }
    let mut bad_cov = 0u64;
    for a in 0..100usize { for b in 0..400usize {
        let inu = univ_pairs.contains(&(a as u32, b as u32));
        let cv = cover[a][b];
        if (inu && cv != 1) || (!inu && cv != 0) { bad_cov += 1; if bad_cov <= 10 { println!("PROBLEM coverage a={} b={} universe={} covered={}", a, b, inu, cv); } }
    } }
    println!("CHECK universe enumerated {} primitive {} (a,b)-pairs {}", univ_en, univ_total, univ_pairs.len());
    println!("CHECK manifest enumerated {} primitive {}  [TODO {} modules {} vectors; DONE-probe {} modules {} vectors; BLOCKED {} intervals {} vectors]", s_en, s_pr, n_todo, p_todo, n_done, p_done, n_blk, p_blk);
    println!("CHECK records in module files (TODO+DONE) {}  certified residual inside blocked intervals {}  certless {}  records+certless {}", s_rec_files, s_rec_blocked, s_nc, s_rec_files + s_rec_blocked + s_nc);
    println!("CHECK coverage violations {}  problems {}", bad_cov, problems);
    let ok = bad_cov == 0 && problems == 0 && s_pr == univ_total && s_en == univ_en;
    println!("CHECK RESULT {}", if ok { "EXACT" } else { "NOT EXACT" });
}
